/** Runs only in an isolated test page; tests actual controls, not fabricated game objects. */
export async function runEquipmentBrowserChecks() {
  const passed = [];
  const check = (value, label) => { if (!value) throw new Error(label); passed.push(label); };
  const eq = (a,b,label) => check(JSON.stringify(a)===JSON.stringify(b),label);
  const click = selector => {
    const node = document.querySelector(selector);
    if (!node || node.disabled) throw new Error(`Control unavailable: ${selector}`);
    node.click();
  };
  const state = () => window.__rotwDebug.snapshot();
  const gear = id => window.__rotwDebug.equipment(id);
  const owner = name => {
    const button=[...document.querySelectorAll('#equipment-owner-tabs button')].find(n=>n.textContent===name);
    if (!button) throw new Error('Missing owner '+name);
    button.click();
  };
  const select = id => click(`#inventory-grid [data-item-id="${id}"]`);
  check(!!window.__rotwDebug?.equipment,'equipment runtime loaded');
  check(document.querySelector('#load').getBoundingClientRect().width>0,'visible load control');
  const initial = state();
  click('#inventory-command');
  eq(document.querySelectorAll('#inventory-grid .inventory-cell').length,40,'40 inventory cells');
  eq(document.querySelectorAll('.d2-empty-weapon-tabs button[data-weapon-set="1"]:not([disabled])').length,2,'one active weapon set in both visual tabs');
  eq(document.querySelectorAll('.d2-empty-weapon-tabs button[data-weapon-set="2"][disabled]').length,2,'unsupported second set cannot change equipment');
  eq(state().save.combat,initial.save.combat,'inspection costs no time');
  eq(gear('korgan').stats.weaponDamage,[1,2],'unarmed 1-2');
  select('korgan.hand_axe');click('#equipment-action');
  eq(gear('korgan').equipment.weapon.id,'korgan.hand_axe','equip same axe identity');
  eq(gear('korgan').stats.weaponDamage,[3,7],'source axe and strength give 3-7');
  eq(document.querySelector('#damage-stat').textContent,'3–7','HUD uses equipment range');
  check(document.querySelector('#skill-card-left .card-copy').textContent.includes('3–7 obr.'),'card uses equipment range');
  eq(state().save.rng,initial.save.rng,'equip does not consume combat RNG');
  select('korgan.starter.short_sword');click('#equipment-action');
  eq(gear('korgan').stats.weaponDamage,[2,9],'swapping sword changes damage');
  check(gear('korgan').items.items.some(i=>i.id==='korgan.hand_axe'),'swapped axe returns to bag');
  click('#equipment-action');
  eq(gear('korgan').stats.weaponDamage,[1,2],'unequip removes weapon contribution');
  select('korgan.hand_axe');click('#equipment-action');
  owner('Hadriel');select('hadriel.targe');
  check(document.querySelector('#equipment-action').disabled,'level 3 shield blocked at level 1');
  check(document.querySelector('#item-details').textContent.includes('poziom 3'),'requirement reason visible');
  select('hadriel.scepter');click('#equipment-action');
  eq(gear('hadriel').stats.weaponDamage,[7,13],'scepter damage source-based');
  select('hadriel.starter.buckler');click('#equipment-action');
  check(!!gear('hadriel').equipment.weapon && !!gear('hadriel').equipment.offhand,'weapon plus shield supported');
  owner('Ormus');const spell=gear('ormus').leftSkill;
  select('ormus.wand');click('#equipment-action');
  eq(gear('ormus').leftSkill,spell,'weapon never increases Teeth');
  owner('Korgan');click('#close-panel');click('#save');
  const key='rotw-prototype-save-v3-equipment-v1-encounters-v1';
  const saved=localStorage.getItem(key);
  check(!!saved,'save button writes data');
  eq(JSON.parse(saved).equipmentSchemaVersion,1,'save contains equipment schema');
  click('#inventory-command');click('[data-equip-slot="weapon"]');click('#equipment-action');click('#close-panel');
  check(!gear('korgan').equipment.weapon,'live weapon removed after save');
  click('#load');eq(gear('korgan').equipment.weapon.id,'korgan.hand_axe','load restores same instance');
  eq(gear('korgan').stats.weaponDamage,[3,7],'load restores damage without stacking');
  check(localStorage.getItem('rotw-prototype-save-v3')===null,'legacy save key not overwritten');
  click('#start-battle');
  check(state().phase==='active' && state().actingUnitId==='korgan','original battle opening preserved');
  click('#inventory-command');owner('Hadriel');click('[data-equip-slot="weapon"]');
  check(document.querySelector('#equipment-action').disabled,'another owner cannot change gear during Korgan turn');
  owner('Korgan');select('korgan.starter.short_sword');click('#equipment-action');
  const history=state().save.combat.commands.history.filter(c=>c.kind==='equipmentChange');
  eq(history.length,1,'one click creates exactly one equipment action');
  eq(history[0].recoveryEnd-history[0].startTick,800,'existing equipment action costs 800ms');
  check(state().actingUnitId!=='korgan','equipment consumes acting decision');
  check(document.querySelector('#equipment-action').disabled,'no repeated free equipment change');
  click('#close-panel');click('#save');const actor=state().actingUnitId;click('#end-turn');click('#load');
  eq(state().actingUnitId,actor,'load restores correct acting unit');
  return passed;
}
